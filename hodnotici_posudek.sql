SELECT id, kezverejnenizadateli

FROM isum.v_bi_UmvHodnoceni

WHERE id in (1209920818,1230055946)





Na projektu nebyly dokončeny hodnotící posudky 2. kroku VH. Následně se žadatel odvolal a PK vrátila projekt k opravnému hodnocení a dokončení hodnotících posudků. Aby mohla být v MS2014+ zadministrována PK, musel být projekt přepnut do stavu PN23a a následně vrácen do PP21. Přepnutím do PN23a se na hodnotících posudcíh vyplný check Ke zveřejnění žadateli na TRUE. Na tento check jsou navázány zveřejněná kritéria při vypořádání žádosti o přezkum v MS2014+.
